param(
  [string]$Version = "0.1.0",
  [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\.."))
)

$ErrorActionPreference = "Stop"
$Harmony = Join-Path $RepoRoot "harmony"
$SignedHap = Join-Path $Harmony "entry\build\default\outputs\default\entry-default-signed.hap"
$ReleaseDir = Join-Path $Harmony "release"
$OutName = "clash-ohos-$Version-signed.hap"
$OutPath = Join-Path $ReleaseDir $OutName

if (-not (Test-Path $SignedHap)) {
  Write-Error "Missing $SignedHap. Run: hvigorw assembleHap -p product=default -p buildMode=release"
}

New-Item -ItemType Directory -Force -Path $ReleaseDir | Out-Null
Copy-Item -Force $SignedHap $OutPath
$hash = Get-FileHash $OutPath -Algorithm SHA256
$hashPath = "$OutPath.sha256"
"$($hash.Hash)  $OutName" | Set-Content -Path $hashPath -Encoding UTF8

Write-Host "Release artifacts:"
Write-Host "  $OutPath"
Write-Host "  $hashPath"
Write-Host ""
Write-Host "GitHub: tag v$Version, upload HAP; Source code zip is auto-generated by GitHub."
